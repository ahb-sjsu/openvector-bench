# entry 512 = cos(pi/2) = 0 exactly, appended for interpolation
_TAB = np.append(_QW, np.float32(0.0))


def cos2pi(x: np.ndarray) -> np.ndarray:
    """cos(2*pi*x) by quarter-wave symmetry over the frozen table.

    Pure float32 arithmetic plus integer gathers; bit-identical on any
    platform for identical inputs.
    """
    x = np.asarray(x, dtype=np.float32)
    t = x - np.floor(x)
    q = t * np.float32(4.0)
    qf = np.floor(q)
    qi = qf.astype(np.int64) & 3
    f = q - qf
    a = np.where((qi & 1) == 0, f, np.float32(1.0) - f)
    idx = a * np.float32(512.0)
    i0 = np.minimum(idx.astype(np.int64), 511)
    frac = (idx - i0).astype(np.float32)
    v = _TAB[i0] * (np.float32(1.0) - frac) + _TAB[np.minimum(i0 + 1, 512)] * frac
    sign = np.where((qi == 1) | (qi == 2), np.float32(-1.0), np.float32(1.0))
    return (v * sign).astype(np.float32)
